"""Write proxy_exports.h: one FWD() line per export of the system vcomp140.dll."""
import os, sys, pefile
pe = pefile.PE(os.environ['SystemRoot'] + r'\System32\vcomp140.dll')
code = [s for s in pe.sections if s.Characteristics & 0x20000000]
names, data = [], []
for e in pe.DIRECTORY_ENTRY_EXPORT.symbols:
    n = e.name.decode()
    (names if any(s.contains_rva(e.address) for s in code) else data).append(n)
print(len(names), 'code exports; data exports:', data)
with open(sys.argv[1], 'w', newline='\r\n') as f:
    f.write('/* generated by gen_exports.py from %SystemRoot%\\System32\\vcomp140.dll */\n')
    for n in names: f.write(f'FWD({n})\n')
